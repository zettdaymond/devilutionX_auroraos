#pragma once

#ifdef AURORA_OS

#include <SDL2/SDL.h>

namespace launcher::aurora {

/// Обложка свёрнутого окна на время игры. Пока работает лаунчер, кадр
/// плитки рисует ImGui (LauncherView::RenderCover); после «Играть»
/// лаунчер умирает, и фирменный кадр для плитки держит движок:
///
/// - лаунчер перед выходом запечатывает обложку — снимает пиксели с
///   бэкбуфера своего рендерера (CaptureFromBackbuffer); буфер — обычная
///   память, он переживает смерть окна лаунчера и создание окна движка;
/// - на время движка стартует второй экземпляр aurora::StateWatch
///   (Init/Shutdown рядом с dx_init/dx_cleanup): его атомарные состояния
///   движок опрашивает перед каждым Present'ом;
/// - в плитке вместо игрового кадра рисуется обложка одним блитом.
///   Кросс-фейда на входе в плитку НЕТ (в отличие от лаунчера):
///   подмешивание SDL_RenderCopy в кадр, где игра нарисована сырым GL
///   через ротатор, смешивало состояния GLES-рендерера и уводило
///   контекст в вечное ожидание frame-callback (чёрный экран движка,
///   сентябрь 2026); кадр только-с-обложкой чист — сырого GL в нём нет.
///
/// Кадр обложки — уже портретный, в ориентации окна: движковый ротатор
/// (TextureRotatorGLES) не нужен, обычный SDL_RenderCopy закрывает кадр.
class GameCover final {
public:
	GameCover() = delete;

	/// Снять пиксели обложки с бэкбуфера рендерера лаунчера. Звать после
	/// отрисовки кадра обложки и ДО SDL_RenderPresent: при двойной
	/// буферизации после обмена читается уже не тот буфер.
	static void CaptureFromBackbuffer(SDL_Renderer *renderer);

	/// Запустить/остановить наблюдателя на фазу движка.
	static void Init();
	static void Shutdown();

	/// Забыть текстуру обложки — рендерер движка пересоздаётся
	/// (ReinitializeRenderer), текстура принадлежит старому.
	static void ResetTexture();

	/// Начало кадра движка (RenderPresent): если вернул true — мы в
	/// плитке, обложка уже нарисована и презентована (либо экран погашен
	/// и кадр рисовать не для кого), игровую часть надо пропустить.
	/// До первого видимого кадра движка (окно ещё поднимается на старте)
	/// всегда false: пользователь ждёт меню, а не обложку.
	[[nodiscard]] static bool BeginCoverFrame(SDL_Renderer *renderer);
};

} // namespace launcher::aurora

#endif
