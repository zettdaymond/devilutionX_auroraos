#ifdef AURORA_OS

#include <SDL2/SDL.h>

namespace launcher::aurora {

/// Обложка свёрнутого окна на время игры. Пока работает лаунчер, кадр
/// плитки рисует ImGui (LauncherView::RenderCover); после «Играть»
/// лаунчер умирает, и фирменный кадр для плитки держит движок:
///
/// - лаунчер перед выходом запечатывает обложку — снимает пиксели с
///   бэкбуфера своего рендерера (CaptureFromBackbuffer); буфер — обычная
///   память, он переживает смерть окна лаунчера и создание окна движка;
/// - на время движка стартует второй экземпляр aurora::StateWatch
///   (Init/Shutdown рядом с dx_init/dx_cleanup): его атомарные состояния
///   движок опрашивает перед каждым Present'ом; под песочницей Авроры
///   (иконочный запуск в firejail) dbus-прокси режет сигналы композитора,
///   поэтому «в плитке» также определяется по потере SDL-фокуса окна
///   (дебаунс 100 мс) — как в Application::IsTiled у лаунчера;
/// - в плитке вместо игрового кадра рисуется обложка одним блитом, а
///   buffer transform окна переводится в NORMAL: окно движка живёт в
///   ландшафтном режиме порта (transform 270 + TextureRotatorGLES), и
///   без переключения композитор (и плитка) показал бы портретную
///   обложку повёрнутой на 90°. При возврате в игру transform
///   возвращается в 270 ДО первого игрового кадра. Кросс-фейда на входе
///   в плитку НЕТ (в отличие от лаунчера): подмешивание SDL_RenderCopy
///   в кадр, где игра нарисована сырым GL через ротатор, смешивало
///   состояния GLES-рендерера и уводило контекст в вечное ожидание
///   frame-callback (чёрный экран движка, сентябрь 2026); кадр
///   только-с-обложкой чист — сырого GL в нём нет.
///
/// Кадр обложки — портретный, как окно лаунчера: обычный SDL_RenderCopy
/// закрывает кадр, движковый ротатор не участвует.
class GameCover final {
public:
	GameCover() = delete;

	/// Снять пиксели обложки с бэкбуфера рендерера лаунчера. Звать после
	/// отрисовки кадра обложки и ДО SDL_RenderPresent: при двойной
	/// буферизации после обмена читается уже не тот буфер.
	static void CaptureFromBackbuffer(SDL_Renderer *renderer);

	/// Запустить/остановить наблюдателя на фазу движка. portraitRotated —
	/// работает ли окно движка в повёрнутом режиме порта (есть ротатор):
	/// только тогда плитке нужно переключение buffer transform.
	static void Init(SDL_Window *window, bool portraitRotated);
	static void Shutdown();

	/// Забыть текстуру обложки — рендерер движка пересоздаётся
	/// (ReinitializeRenderer), текстура принадлежит старому.
	static void ResetTexture();

	/// Начало кадра движка (RenderPresent): если вернул true — мы в
	/// плитке, обложка уже нарисована и презентована (либо экран погашен
	/// и кадр рисовать не для кого), игровую часть надо пропустить.
	/// До первого видимого кадра движка (окно ещё поднимается на старте)
	/// всегда false: пользователь ждёт меню, а не обложку.
	[[nodiscard]] static bool BeginCoverFrame(SDL_Renderer *renderer);
};

} // namespace launcher::aurora

#endif
