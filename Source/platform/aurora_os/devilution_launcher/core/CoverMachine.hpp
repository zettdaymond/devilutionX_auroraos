#pragma once

namespace launcher::aurora {

/// События, питающие машину обложки плитки на фазе движка.
enum class CoverEvent {
	FocusLost,   ///< окно потеряло фокус (сворачивание в плитку или блокировка)
	FocusGained, ///< окно вернуло фокус
	DisplayOff,  ///< экран погас
	DisplayOn,   ///< экран включился
};

/// Решение машины для очередного кадра движка.
enum class CoverAction {
	RenderGame,    ///< рисуем игровой кадр (обложка снята, transform 270)
	RenderCover,   ///< рисуем обложку (transform NORMAL)
	RenderNothing, ///< кадров нет (экран погашен)
};

/// Событийная стейтмашина обложки плитки на фазе движка. Никаких таймеров:
/// только события и переходы. Topmost/tklock композитора под песочницей
/// Авроры недоступны, поэтому вход — SDL-фокус окна и состояние дисплея.
///
/// Состояния:
///  - Starting          — старт движка, окно ещё не получало фокус: рисуем
///                         игру; FocusLost игнорируем (подъём окна на старте
///                         мельком теряет фокус, меню закрывать нельзя);
///  - Game              — игра видима: игровые кадры;
///  - Cover             — фокус потерян при горящем экране: свернулись в
///                         плитку либо показан локскрин (пока неотличимо и
///                         не важно — за локскрином обложку не видно);
///  - Dark              — экран погашен: кадров нет;
///  - GameAwaitingFocus — экран включился после гашения, фокус ещё не
///                         вернулся (поток «блокировка»): рисуем игровой
///                         кадр за локскрином, чтобы его раскрытие показало
///                         игру, а не обложку; обложка не включается, пока
///                         фокус не вернётся.
///
/// Ключевой переход — Cover + DisplayOff: гашение раньше возврата фокута
/// означает блокировку, карточку из буфера убираем (действие этого вызова
/// Handle — RenderGame: один игровой кадр), дальше кадры не нужны.
class CoverMachine final {
public:
	CoverMachine() = default;

	/// Принять событие и перевести состояние. Каждый вызов логируется:
	/// что пришло, где были, куда перешли. Одноразовое действие перехода
	/// (кадр-замена при гашении карточки) забирается следующим NextAction().
	void Handle(CoverEvent event);

	/// Действие для очередного кадра; одноразовые действия переходов
	/// отдаются ровно один раз (первый вызвавший кадр).
	[[nodiscard]] CoverAction NextAction();

	/// Стабильное действие текущего состояния, без одноразовых.
	[[nodiscard]] CoverAction Action() const;

	/// Сброс в начальное состояние (Starting).
	void Reset();

private:
	enum class State { Starting, Game, Cover, Dark, GameAwaitingFocus };

	[[nodiscard]] static const char *StateName(State state);

	State m_state = State::Starting;
	bool m_swapFramePending = false;
};

} // namespace launcher::aurora
